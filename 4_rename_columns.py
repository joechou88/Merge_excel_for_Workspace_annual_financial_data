import os
import re
import glob
import logging
import pandas as pd
from datetime import datetime
import config

def get_col_letter(n):
    result = ""
    while n >= 0:
        result = chr(65 + (n % 26)) + result
        n = n // 26 - 1
    return result

timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
log_filename = f"4_rename_columns_{timestamp}.txt"

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
    handlers=[
        logging.FileHandler(log_filename, encoding='utf-8'),
        logging.StreamHandler()
    ]
)

base_directory = './raw_data'
search_pattern = os.path.join(base_directory, f"All*Countries_{config.START_YEAR}-{config.END_YEAR}.csv")
matched_files = glob.glob(search_pattern)

if not matched_files:
    logging.warning("No target files found to rename columns.")
else:
    input_filepath = matched_files[0]
    logging.info(f"Reading: {input_filepath}")
    
    # Added low_memory=False to resolve DtypeWarning for mixed types
    df = pd.read_csv(input_filepath, low_memory=False)
    
    # Identify duplicate columns generated by pandas (ending with .1, .2, etc.)
    columns_to_drop = [column for column in df.columns if re.search(r'\.\d+$', column)]
    
    if columns_to_drop:
        logging.info(f"Dropping {len(columns_to_drop)} duplicate columns...")
        for col in columns_to_drop:
            col_index = df.columns.get_loc(col)
            col_letter = get_col_letter(col_index)
            logging.info(f"  Column {col_letter}: '{col}' dropped")
            
        df.drop(columns=columns_to_drop, inplace=True)

    rename_mapping = {}
    for column in df.columns:
        if column == 'Type':
            rename_mapping[column] = 'DSCD'
            continue
            
        # Pattern: X(WC01254) -> WC01254
        match_simple = re.match(r"^X\((WC\d+)\)$", column)
        if match_simple:
            rename_mapping[column] = match_simple.group(1)
            continue
            
        # Pattern: X(WC06705)~U, X(WC18545)~U$, X(WC04601)~US -> XWCXXXXXU
        match_complex = re.match(r"^X\((WC\d+)\)~.*$", column)
        if match_complex:
            rename_mapping[column] = f"X{match_complex.group(1)}U"

    if rename_mapping:
        logging.info(f"Renaming {len(rename_mapping)} columns...")
        for old_col, new_col in rename_mapping.items():
            col_index = df.columns.get_loc(old_col)
            col_letter = get_col_letter(col_index)
            logging.info(f"  Column {col_letter}: '{old_col}' -> '{new_col}'")
        
        df.rename(columns=rename_mapping, inplace=True)
    
    output_filename = os.path.basename(input_filepath).replace('.csv', '_renamed.csv')
    output_filepath = os.path.join(base_directory, output_filename)
    
    logging.info(f"Saving processed data to {output_filename}")
    try:
        df.to_csv(output_filepath, index=False, encoding='utf-8-sig')
        logging.info("--- Column renaming completed ---")
    except Exception as error:
        logging.error(f"Failed to save {output_filename}: {error}")
        